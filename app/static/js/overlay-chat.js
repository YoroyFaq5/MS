// Aggregated multi-stream chat — idle-hero "chat" slot (Live-Commentators
// only). Embeds the StreamVI widget (aggregates chat across all of the
// tournament's simultaneous streams, not just one Twitch channel) as a
// single persistent <iframe>, created ONCE and then MOVED (not recreated)
// into whichever fresh #ovl-chat-frame container shows up after each full
// fragment DOM replace (see overlay.js's poll() — a `sig` change, e.g. a
// game starting or finishing, wholesale replaces #overlay-root's content
// several times an hour during a live broadcast). Moving the same DOM node
// preserves the iframe's browsing context (its own connection/scrollback);
// writing a fresh <iframe src="..."> into the template every time would
// force it to reload from scratch on every single replace — the "chat
// keeps clearing itself" symptom the previous Twitch-only implementation
// was intermittently hitting.
window.MSOverlayChat = (function () {
  // Verbatim URL as generated by StreamVI's own embed dashboard — the
  // unescaped '#' in the color params technically starts a URL fragment
  // rather than query params per spec, but this is exactly the string
  // StreamVI hands out for embedding (and what any browser, including
  // OBS's CEF one, resolves the same way), so it's reproduced as-is
  // rather than "corrected" into something never actually tested there.
  const WIDGET_URL = 'https://chat.streamvi.io/?lang=ru&mode=widget&elements=input,emoji&token=ch_b7e4bd11pimNG9Ej2568smwMWoIondMdQbKVmclj&background=#141414&color=#FFFFFF&nameColor=#ADADAD&messageBoxColor=#FFFFFF99&scale=211&messageMargin=100&scrollbarVisibility=visible&inputVisibility=visible&messageAnimation=none&messageAlignment=bottom&messageTime=true&messageHidden=none&messageHiddenDelay=2&messageIcon=platform&messageTheme=compact';

  let iframe = null;

  function mountEl() { return document.getElementById('ovl-chat-frame'); }

  function ensureIframe() {
    if (iframe) return iframe;
    iframe = document.createElement('iframe');
    iframe.src = WIDGET_URL;
    iframe.title = 'Чат';
    iframe.style.cssText = 'width:100%;height:100%;border:0;display:block;';
    iframe.setAttribute('allow', 'clipboard-write');
    return iframe;
  }

  // Called by overlay.js both on initial page load and after every full
  // fragment DOM replace (mirrors window.MSBroadcastScenes.init()). Only
  // ever MOVES the one persistent iframe node into the current mount
  // point — never touches iframe.src again once set, so the widget's own
  // connection/session is never interrupted by our polling.
  function init() {
    const mount = mountEl();
    if (!mount) return; // Live-Game page, or this tournament never rendered the chat slot
    const el = ensureIframe();
    if (el.parentElement !== mount) mount.appendChild(el);
  }

  return { init: init };
})();
